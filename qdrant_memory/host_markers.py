"""Text the host writes into ``state.db`` ``messages.content`` that nobody said.

Hermes stores its own scaffolding as ordinary ``user`` (sometimes ``assistant``) rows:
context-compaction handoffs, gateway notifications, background-process and delegation
reports, mid-turn steer frames, recalled-memory fences, skill and cron prompts, model
and surface switch notices. None of it is something a person or the assistant said,
and much of it is instruction-shaped ("Respond ONLY to ...", "You are running as a
scheduled cron job"). Replayed by recall into another conversation it reads as live
work, which is how foreign tasks get resumed after a compaction.

``is_host_injected`` decides per message. The markers are the host's own constants
(Hermes core, read on 2026-11-15; see docs/session-recall-prefetch.md for file:line):
openers that start the row after an optional gateway sender tag (``[Name] ``) and an
optional Discord routing note, and frames that can sit anywhere in a row (appended
notification footers, summaries merged after a real message, memory fences, steer
frames). A row is judged as a whole: any frame anywhere drops the whole row, because a
window can cut a row at any point and a partial frame is not reliably recognizable.

A real message that merely quotes a short marker (discussing the host's code) is kept:
the anywhere-frames are the full host sentences, not the bracketed labels.

``recall_query`` applies the same markers to the incoming message automatic recall
searches with: ``""`` for a host-generated message, the user's words for a wrapped one.
"""
from __future__ import annotations

import re

# ``gateway/session.py`` prefixes a shared-session speaker as ``[Name] text``; Slack adds
# `` | Slack user <@id>``. Names are tag-safe (no brackets or newlines).
_SENDER_TAG_RE = re.compile(r"\A\[[^\[\]\n]{1,80}\] (?=\S)")
# ``gateway/run_inbound.py`` ``discord_triggering_note``: rides in front of the user text.
_TRIGGER_NOTE_RE = re.compile(r"\A\[Triggering message id: [^\n]*\]\s*")

# Openers: the row (after the tags above) starts with one of these.
_OPENERS = (
    # agent/context_compressor.py SUMMARY_PREFIX, LEGACY_SUMMARY_PREFIX, _MERGED_PRIOR_CONTEXT_HEADER
    # (core's own synthetic-row test matches the bare "[CONTEXT" opener)
    "[CONTEXT",
    "[PRIOR CONTEXT",
    "[END OF PRIOR CONTEXT",
    # agent/context_compressor.py _SYNTHETIC_USER_ROW_PREFIXES and
    # agent/prompt_builder.py CONTROL_FRAME_OPENERS
    "[System:",
    "[System note:",
    "[SYSTEM]",
    "[Runtime note:",
    "[IMPORTANT:",
    "[ASYNC DELEGATION",
    "[ASYNC COMPLETE",
    "[OUT-OF-BAND",
    "[/OUT-OF-BAND",
    "[Your active task list",
    "[Planning state preserved",
    "Cronjob Response:",
    # tools/process_registry_notifications.py heartbeat; older gateways' completion line
    "[Background process ",
    "\u2705 Background task",
    # gateway/run_inbound.py and gateway/run.py media notes (host descriptions of attachments)
    "[The user sent ",
    # tools/tts_streaming.py, tools/voice_live.py, context_compressor _COMPRESSION_NOTE
    "[Note: ",
    # agent/memory_context.py fence
    "<memory-context>",
    # agent/context_compressor.py: the active request restated after a compaction
    "[STILL IN PROGRESS",
    # gateway/run_busy.py goal nudge; cron/scheduler_delivery.py; tui_gateway/methods_prompt.py;
    # discord adapter / gateway/relay/ws_transport.py channel transcript
    "[Continuing toward your standing goal]",
    "[Cron delivery:",
    "[The user reacted ",
    "[Recent channel messages]",
    # hermes-lcm plugin (reconcile.py, engine.py): preserved objective and DAG summaries
    "[Current user objective preserved",
    # retired hermes-dynamic-focus-pruning plugin, still present in older rows
    "[HDFP ",
    "[Internal HDFP",
)
# ``[Recent Summary (d0, node 12)]``, ``[Session Arc Summary ...]``, ``[Depth-3 Summary ...]``.
_LCM_SUMMARY_RE = re.compile(r"\A\[(?:Recent|Session Arc|Durable|Depth-\d+) Summary \(d\d+, node [^)\]]*\)\]")

# Frames that mark a row wherever they appear (full host sentences, not bare labels).
_ANYWHERE = (
    # agent/context_compressor.py SUMMARY_PREFIX (its first sentence) and the merge delimiter
    "[CONTEXT COMPACTION \u2014 REFERENCE ONLY] Earlier turns were compacted",
    "[END OF PRIOR CONTEXT \u2014 COMPACTION SUMMARY BELOW]",
    "[PRIOR CONTEXT \u2014 for reference only; not a new message]",
    "--- END OF CONTEXT SUMMARY \u2014 respond to the message below",
    "[STILL IN PROGRESS \u2014 this is the active request, restated after the",
    # gateway/run_notifications.py INTERNAL_NOTIFICATION_FOOTER (appended)
    "[INTERNAL NOTIFICATION \u2014 generated by the Hermes gateway",
    # agent/prompt_builder.py STEER_MARKER_OPEN
    "[OUT-OF-BAND USER MESSAGE \u2014 a direct message from the user",
    # agent/memory_context.py build_memory_context_block
    "[System note: The following is recalled memory context",
    "<memory-context>",
)


def _heads(text: str) -> list[str]:
    """The row's start, then its start after each leading sender tag / routing note.

    A bracketed host label (``[CONTEXT COMPACTION] ...``) has the shape of a sender tag,
    so every stage is checked, not only the fully stripped one.
    """
    heads = [text.lstrip()]
    for _ in range(3):
        stripped = _TRIGGER_NOTE_RE.sub("", heads[-1], count=1)
        stripped = _SENDER_TAG_RE.sub("", stripped, count=1).lstrip()
        if stripped == heads[-1]:
            break
        heads.append(stripped)
    return heads


def _strip_tags(text: str) -> str:
    return _heads(text)[-1]


def is_host_injected(content: object) -> bool:
    """True when a stored message is host scaffolding, not something anyone said."""
    text = str(content or "")
    if not text.strip():
        return False
    if any(frame in text for frame in _ANYWHERE):
        return True
    return any(head.startswith(_OPENERS) or _LCM_SUMMARY_RE.match(head) for head in _heads(text))


# Host frames that wrap a real user message (the user's words follow, or sit inside):
# agent/prompt_builder.py STEER_MARKER_OPEN / STEER_MARKER_CLOSE (format_steer_marker), and the
# attachment notes gateway/run_inbound.py, gateway/run.py and gateway/run_inbound_transcription.py
# put in front of the caption (an image note is followed by its "closer look" line).
_STEER_OPEN = "[OUT-OF-BAND USER MESSAGE \u2014 a direct message from the user"
_STEER_CLOSE = "[/OUT-OF-BAND USER MESSAGE]"
_ATTACHMENT_NOTES = ("[The user sent ", "[If you need a closer look, use vision_analyze")


def _frame_end(text: str) -> int:
    """Index just past the bracket frame that opens ``text``; -1 when it never closes."""
    depth = 0
    for index, char in enumerate(text):
        if char == "[":
            depth += 1
        elif char == "]":
            depth -= 1
            if depth == 0:
                return index + 1
    return -1


def recall_query(content: object) -> str:
    """The words automatic recall may search with: ``""`` for a host-generated message.

    The host wrappers around a real message (sender tag, Discord routing note, steer frame,
    attachment notes) are taken off; what is left is the user's words. A message that is,
    or after those wrappers starts with, any other host frame is host-generated and yields
    ``""``, as does a frame that never closes (fail closed).
    """
    text = str(content or "").strip()
    for _ in range(16):
        if text.startswith((_STEER_OPEN, *_ATTACHMENT_NOTES)):
            end = _frame_end(text)
            if end < 0:
                return ""
            peeled = text[end:]
            if text.startswith(_STEER_OPEN):
                before, close, after = peeled.rpartition(_STEER_CLOSE)
                peeled = before + after if close else peeled
        elif text.startswith(_OPENERS) or _LCM_SUMMARY_RE.match(text):
            return ""
        else:
            # One wrapper per pass, so each stage gets the opener check above.
            peeled = _TRIGGER_NOTE_RE.sub("", text, count=1)
            if peeled == text:
                peeled = _SENDER_TAG_RE.sub("", text, count=1)
        if peeled == text:
            break
        text = peeled.strip()
    return "" if not text or is_host_injected(text) else text
