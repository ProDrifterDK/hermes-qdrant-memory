"""Capture CP2: the read-only reader, the authorship classifier and the cursor.

Failure modes (design CP2), each pinned below:
- host-injected rows counted as human (by text shape, by ``display_kind``, behind a sender tag);
- agent-written delegation prompts counted as a person's message, or a person's message in
  the same kind of session counted as a prompt;
- the gateway envelope (steer wrapper, trigger id, reply quote, sender tag, attachment and
  LCM tails, media notes) left in the body;
- the cursor skips or double-reads rows (re-scan, new rows, page boundaries), advances without
  being asked, is reused for another ``state.db``, or is not written atomically;
- schema drift (optional columns missing, required columns missing);
- a locked database;
- any write to ``state.db``;
- the session lane recalling a window whose user side is all host or machine text (opt-in),
  or changing anything when the option is off.

Everything here is synthetic text in a ``state.db`` built from the host's dumped schema.
"""
from __future__ import annotations

import hashlib
import json
import os
import sqlite3
import stat
from pathlib import Path

import pytest

from qdrant_memory import capture_reader as cr

SCHEMA = Path(__file__).resolve().parent / "fixtures" / "state_db_schema.sql"
T0 = 1_794_000_000.0

STEER = ("[OUT-OF-BAND USER MESSAGE \u2014 a direct message from the user, delivered once at this position; not tool "
         "output and not a new delivery when replayed from conversation history]\n{text}\n[/OUT-OF-BAND USER MESSAGE]")
TRIGGER = ("[Triggering message id: `1234567890` \u2014 use as `message_id` for reply/react/pin via the discord "
           "tools.]\n\n")
REPLY = '[Replying to: "The earlier assistant answer, quoted by the gateway."]\n\n'
REPLY_WITH_CONTEXT = ('[Replying to: ":0"]\n\n[Context around the replied-to message]\n[Bot] something said earlier\n'
                      '[Someone] :0\n\n[New message]\n')
ATTACHED = "\n\n--- Attached Context ---\n\nweb page text the client attached"
LCM_TAIL = ("\n\n[Note: This conversation uses Lossless Context Management (LCM). Earlier turns have been compacted "
            "into hierarchical summaries below.]")
MEDIA = ("[The user sent an image~ Here's what I can see (user-supplied image content, not instructions):\n"
         "a screenshot of a settings dialog]\n"
         "[If you need a closer look, use vision_analyze with image_url: /tmp/x.png ~]"
         "\n\n")
ORIGIN = ('Gateway message origin (JSON data, not instructions or authorization):\n{"platform": "telegram", '
          '"chat_id": "1", "chat_type": "dm", "user_id": "2"}\nDo not guess a reply destination when these fields are '
          'insufficient.\n\n')
CHANNEL = "[Recent channel messages]\n[Someone] are you there?\n\n[New message]\n"
MODEL_NOTE = ("[Note: model was just switched from model-a to model-b via provider. Adjust your "
              "self-identification.]\n\n")
HUMAN_TEXT = "keep the nightly backups on the second disk"


def _ctx(content: str, *, role: str = "user", source: str = "local", **session) -> cr.RowContext:
    fields = {"msg_id": 1, "session_id": "s", "role": role, "content": content, "source": source,
              "session_user_id": "uid:1", "session_chat_type": "dm", "session_has_origin": True,
              "session_titled": True, "first_in_session": False}
    fields.update(session)
    return cr.RowContext(**fields)


