def _run_cli(argv, monkeypatch, home, db):
    import argparse
    import io

    import cli
    from qdrant_memory.cli_core import execute_command

    monkeypatch.setenv("HERMES_HOME", home)
    monkeypatch.setattr("qdrant_memory.config._load_hermes_config",
                        lambda: {"qdrant_memory": {"session_recall_state_db": str(db)}})
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest="command")
    cli.register_cli(sub.add_parser("qdrant"))
    out, err = io.StringIO(), io.StringIO()

    def no_provider():
        raise AssertionError("capture scan must not build the provider")

    code = execute_command(parser.parse_args(["qdrant", *argv]), provider_factory=no_provider, stdout=out, stderr=err)
    return code, out.getvalue(), err.getvalue()


def test_cli_capture_scan_counts_and_moves_the_cursor_only_with_advance(db, tmp_path, monkeypatch):
    home = _home(tmp_path)

    code, out, _ = _run_cli(["capture", "scan", "--json"], monkeypatch, home, db)
    payload = json.loads(out)
    assert code == 0 and payload["by_class"] == {"host": 1, "machine": 4, "human": 2}
    assert payload["cursor"]["advanced"] is False and not cr.cursor_path(home).exists()

    code, out, _ = _run_cli(["capture", "scan", "--advance"], monkeypatch, home, db)
    assert code == 0 and "(advanced)" in out and "human 2" in out
    code, out, _ = _run_cli(["capture", "scan", "--json", "--advance"], monkeypatch, home, db)
    assert json.loads(out)["rows"] == 0
