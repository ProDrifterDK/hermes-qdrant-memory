# --- reader and cursor on a synthetic state.db --------------------------------------------


def _make_db(path: Path) -> sqlite3.Connection:
    conn = sqlite3.connect(path)
    conn.executescript(SCHEMA.read_text(encoding="utf-8"))
    return conn


def _session(conn, sid, source="local", *, identity=True, title: str | None = "", parent=None):
    title = f"title {sid}" if title == "" else title
    conn.execute("INSERT INTO sessions (id, source, user_id, chat_type, origin_json, title, parent_session_id, "
                 "started_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
                 (sid, source, "uid:1" if identity else None, "dm" if identity else None,
                  '{"platform": "x"}' if identity else None, title, parent, T0))


def _message(conn, sid, role, content, ts_offset=0.0, display_kind=None):
    cur = conn.execute("INSERT INTO messages (session_id, role, content, timestamp, message_uid, display_kind) "
                       "VALUES (?, ?, ?, ?, ?, ?)", (sid, role, content, T0 + ts_offset, os.urandom(6).hex(),
                                                     display_kind))
    return int(cur.lastrowid)


@pytest.fixture
def db(tmp_path):
    path = tmp_path / "state" / "state.db"
    path.parent.mkdir()
    conn = _make_db(path)
    _session(conn, "human-1")
    _message(conn, "human-1", "user", TRIGGER + "[Alan] " + HUMAN_TEXT, 1)
    _message(conn, "human-1", "assistant", "Noted.", 2)
    _message(conn, "human-1", "tool", "tool output, not eligible", 3)
    _message(conn, "human-1", "user", "[IMPORTANT: Background process proc_1 completed normally]", 4)
    _message(conn, "human-1", "user", "   ", 5)  # not eligible: blank
    _session(conn, "brief-1", "telegram", identity=False, title=None)
    _message(conn, "brief-1", "user", "Review the diff and report blockers.", 6)
    _message(conn, "brief-1", "assistant", "Two blockers.", 7)
    _message(conn, "brief-1", "user", "gracias", 8)
    _session(conn, "cron-1", "cron")
    _message(conn, "cron-1", "user", "Run the nightly check.", 9)
    conn.commit()
    conn.close()
    return path


def _home(tmp_path) -> str:
    home = tmp_path / "home"
    home.mkdir(exist_ok=True)
    return str(home)


def _listing(directory: Path) -> list[tuple[str, int, int]]:
    return sorted((p.name, p.stat().st_size, p.stat().st_mtime_ns) for p in directory.iterdir())


def test_scan_classifies_every_eligible_row_and_never_writes_state_db(db, tmp_path):
    before_listing, before_sha = _listing(db.parent), hashlib.sha256(db.read_bytes()).hexdigest()

    result = cr.scan(str(db), _home(tmp_path))

    assert result["rows"] == 7
    assert result["by_class"] == {"host": 1, "machine": 4, "human": 2}
    assert result["by_kind"]["machine:delegation_brief"] == 1
    assert result["by_kind"]["machine:non_interactive_source"] == 1
    assert result["cursor"]["advanced"] is False and result["cursor"]["after"] == 0
    assert not Path(result["cursor"]["path"]).exists()
    assert _listing(db.parent) == before_listing
    assert hashlib.sha256(db.read_bytes()).hexdigest() == before_sha
    assert "Review the diff" not in json.dumps(result)


def test_records_carry_the_cleaned_human_body(db):
    records = [cr.record_for(c) for c in cr.read_rows(str(db), 0, 10**9)]
    human = [r for r in records if r.classification == "human"]
    assert [(r.session_id, r.body, r.sender) for r in human] == [("human-1", HUMAN_TEXT, "Alan"),
                                                                 ("brief-1", "gracias", "")]


def test_advance_then_rescan_reads_nothing_and_new_rows_exactly_once(db, tmp_path):
    home = _home(tmp_path)
    first = cr.scan(str(db), home, advance=True)
    again = cr.scan(str(db), home, advance=True)
    conn = sqlite3.connect(db)
    new_ids = [_message(conn, "human-1", "user", "one more thing", 20),
               _message(conn, "human-1", "assistant", "ok", 21)]
    conn.commit()
    conn.close()
    third = cr.scan(str(db), home, advance=True)

    assert first["rows"] == 7 and first["cursor"]["after"] == first["snapshot_max_id"]
    assert again["rows"] == 0 and again["cursor"]["before"] == again["cursor"]["after"] == first["cursor"]["after"]
    assert third["rows"] == 2 and (third["first_msg_id"], third["last_msg_id"]) == tuple(new_ids)


def test_paging_neither_skips_nor_repeats_rows(db):
    every = [c.msg_id for c in cr.read_rows(str(db), 0, 10**9, page_size=1000)]
    paged = [c.msg_id for c in cr.read_rows(str(db), 0, 10**9, page_size=2)]
    assert paged == every and len(set(paged)) == len(paged) == 7


def test_since_days_bounds_the_scan_by_timestamp(db, tmp_path):
    result = cr.scan(str(db), _home(tmp_path), since_days=(T0 + 10 - (T0 + 6.5)) / 86400, now=T0 + 10)
    assert result["rows"] == 3  # rows at +7, +8, +9


def test_the_cursor_file_is_atomic_private_and_bound_to_its_state_db(db, tmp_path):
    home = _home(tmp_path)
    cr.scan(str(db), home, advance=True)
    path = cr.cursor_path(home)
    assert stat.S_IMODE(path.stat().st_mode) == 0o600
    assert [p.name for p in path.parent.iterdir()] == ["cursor.json"]  # no temp file left behind
    other = tmp_path / "other.db"
    _make_db(other).close()
    with pytest.raises(cr.CaptureReadError, match="another state.db"):
        cr.scan(str(other), home)


def test_a_cursor_ahead_of_state_db_is_refused(db, tmp_path):
    home = _home(tmp_path)
    cr.save_cursor(cr.cursor_path(home), str(db), 10**6)
    with pytest.raises(cr.CaptureReadError, match="ahead"):
        cr.scan(str(db), home)


def test_optional_columns_missing_still_read(tmp_path):
    path = tmp_path / "old.db"
    conn = sqlite3.connect(path)  # an older host: no display_kind, title, origin_json, user_id, chat_type
    conn.executescript(
        "CREATE TABLE sessions (id TEXT PRIMARY KEY, source TEXT, parent_session_id TEXT, started_at REAL);"
        "CREATE TABLE messages (id INTEGER PRIMARY KEY AUTOINCREMENT, session_id TEXT, role TEXT, content TEXT, "
        "timestamp REAL, message_uid TEXT);")
    conn.execute("INSERT INTO sessions (id, source, started_at) VALUES (?, ?, ?)", ("a", "telegram", T0))
    conn.execute("INSERT INTO messages (session_id, role, content, timestamp, message_uid) VALUES (?, ?, ?, ?, ?)",
                 ("a", "user", "Review the diff.", T0, "u1"))
    conn.commit()
    conn.close()

    (row,) = list(cr.read_rows(str(path), 0, 10))

    assert cr.classify_row(row).kind == "delegation_brief"


def test_required_columns_missing_is_a_read_error(tmp_path):
    path = tmp_path / "broken.db"
    conn = sqlite3.connect(path)
    conn.executescript("CREATE TABLE sessions (id TEXT); "
                       "CREATE TABLE messages (id INTEGER PRIMARY KEY, session_id TEXT);")
    conn.close()
    with pytest.raises(cr.CaptureReadError, match="schema_unsupported"):
        cr.scan(str(path), _home(tmp_path))


def test_a_locked_state_db_is_a_read_error_and_the_cursor_stays(db, tmp_path):
    home = _home(tmp_path)
    cr.scan(str(db), home, advance=True)
    saved = cr.cursor_path(home).read_text()
    writer = sqlite3.connect(db, isolation_level=None)
    writer.execute("BEGIN EXCLUSIVE")
    try:
        with pytest.raises(cr.CaptureReadError):
            cr.scan(str(db), home, advance=True)
    finally:
        writer.execute("ROLLBACK")
        writer.close()
    assert cr.cursor_path(home).read_text() == saved


